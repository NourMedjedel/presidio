"""Reproduce the project-authored v1 corpus without using detector outputs."""

import argparse
import hashlib
import json
from pathlib import Path

REFERENCE = (
    Path(__file__).resolve().parents[2]
    / "samples/python/french_conversation_phone/fixtures"
)
# Project-authored spelling/annotation table, separate from the normalizer.
# This is not independently reviewed validation data.
PAIRS = (
    ("12", "douze"),
    ("13", "treize"),
    ("14", "quatorze"),
    ("15", "quinze"),
    ("16", "seize"),
    ("17", "dix-sept"),
    ("18", "dix-huit"),
    ("19", "dix-neuf"),
    ("20", "vingt"),
    ("21", "vingt et un"),
    ("22", "vingt-deux"),
    ("34", "trente-quatre"),
    ("45", "quarante-cinq"),
    ("56", "cinquante-six"),
    ("67", "soixante-sept"),
    ("71", "soixante et onze"),
    ("78", "soixante-dix-huit"),
    ("80", "quatre-vingts"),
    ("91", "quatre-vingt-onze"),
    ("99", "quatre-vingt-dix-neuf"),
)
DIGITS = (
    "zéro",
    "un",
    "deux",
    "trois",
    "quatre",
    "cinq",
    "six",
    "sept",
    "huit",
    "neuf",
)


def _annotate(markup):
    text, spans = "", []
    while "[[" in markup:
        before, rest = markup.split("[[", 1)
        value, markup = rest.split("]]", 1)
        text += before
        start = len(text)
        text += value
        spans.append([start, len(text)])
    return text + markup, spans


def generate_data(destination: Path) -> dict:
    """Regenerate v1 JSONL splits and verify their original frozen hashes.

    The reference manifest describes the historical v1 corpus. Copying that
    metadata preserves the old evaluation pins; cases themselves are generated
    from the authored templates below, not copied or labelled by the detector.

    :param destination: New output directory. Existing data are never overwritten.
    :return: The v1 manifest with per-split counts and hashes.
    :raises ValueError: If generated bytes differ from the frozen v1 corpus.
    :raises FileExistsError: If the output directory already exists.
    """
    cases = {"development": [], "release": []}
    for i, (value, pair) in enumerate(PAIRS):
        phone = "06123456" + value
        groups = "zéro six, douze, trente-quatre, cinquante-six, " + pair
        digit_words = " ".join(DIGITS[int(d)] for d in phone)
        prompt = "AGENT: Quel est votre numéro de téléphone ?\n"
        examples = [
            (
                "digits",
                "development",
                prompt
                + "CLIENT: [["
                + " ".join(phone[j : j + 2] for j in range(0, 10, 2))
                + "]].",
            ),
            (
                "spoken_digits",
                "development",
                prompt + "CLIENT: [[" + digit_words + "]].",
            ),
            ("spoken_groups", "development", prompt + "CLIENT: [[" + groups + "]]."),
            (
                "split_answer",
                "release",
                prompt + "CLIENT: [[zéro six, douze, trente-quatre]]\nAGENT: Oui.\n"
                "CLIENT: [[cinquante-six, " + pair + "]].",
            ),
            (
                "international",
                "release",
                prompt
                + "CLIENT: [[+33 six, douze, trente-quatre, cinquante-six, "
                + pair
                + "]].",
            ),
            (
                "quantity",
                "development",
                "AGENT: Combien de participants ?\nCLIENT: " + pair + ".",
            ),
            (
                "price",
                "development",
                "AGENT: Quel est le prix ?\nCLIENT: " + pair + " euros.",
            ),
            (
                "date",
                "development",
                "AGENT: À quelle date ?\nCLIENT: " + str(i + 1) + "/12/2026.",
            ),
            (
                "order_reference",
                "development",
                "AGENT: Quel est votre numéro de commande ?\nCLIENT: " + groups + ".",
            ),
            (
                "topic_change",
                "release",
                prompt + "AGENT: Combien de participants ?\nCLIENT: " + groups + ".",
            ),
            ("unknown_speaker", "release", prompt + "TIERS: " + groups + "."),
        ]
        for family, split, markup in examples:
            text, spans = _annotate(markup)
            row = {
                "id": f"{family}-{i:02d}",
                "family": family,
                "text": text,
                "expected_spans": spans,
            }
            if spans:
                row["canonical_phone"] = (
                    "+336123456" + value if family == "international" else phone
                )
            cases[split].append(row)
    manifest_bytes = (REFERENCE / "manifest.json").read_bytes()
    manifest = json.loads(manifest_bytes)
    payloads = {}
    for split, rows in cases.items():
        name = split + ".jsonl"
        data = "".join(
            json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n"
            for row in rows
        ).encode()
        if hashlib.sha256(data).hexdigest() != manifest["files"][name]["sha256"]:
            raise ValueError(
                "Generated data differ from frozen v1; version the corpus "
                "instead of replacing it."
            )
        payloads[name] = data
    destination.mkdir(parents=True, exist_ok=False)
    for name, data in payloads.items():
        (destination / name).write_bytes(data)
    (destination / "manifest.json").write_bytes(manifest_bytes)
    return manifest


def main() -> None:
    """Generate fixed synthetic cases into a new directory."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        manifest = generate_data(args.output)
    except FileExistsError:
        parser.error(
            "Output directory exists; choose a new directory to preserve data."
        )
    for name, metadata in manifest["files"].items():
        print(f"{name}: {metadata['conversations']} conversations; SHA-256 verified")
    print("Project-authored synthetic data only; never contact generated numbers.")


if __name__ == "__main__":
    main()
